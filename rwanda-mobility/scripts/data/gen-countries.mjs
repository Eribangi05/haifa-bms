// Builds the country lists used by the app (names in Kinyarwanda, French and English with the dial code) and by the server (dial codes only).
// Input: scripts/data/dial-codes.json (ISO 3166 alpha-2 + calling code; North American islands carry their area code) and scripts/data/country-rw.json (Kinyarwanda names).
// English and French names come from the platform's own country names (Intl.DisplayNames). Run: node scripts/data/gen-countries.mjs
import fs from 'node:fs';
const dir = new URL('.', import.meta.url).pathname;
const codes = JSON.parse(fs.readFileSync(dir + 'dial-codes.json', 'utf8')), rw = JSON.parse(fs.readFileSync(dir + 'country-rw.json', 'utf8'));
const en = new Intl.DisplayNames(['en'], { type: 'region' }), fr = new Intl.DisplayNames(['fr'], { type: 'region' });
const fix = { XK: ['Kosovo', 'Kosovo'], EH: ['Western Sahara', 'Sahara occidental'] };
const rows = codes.map(([iso, dial]) => { const [e, f] = fix[iso] ?? [en.of(iso), fr.of(iso)]; if (!rw[iso]) throw new Error('missing Kinyarwanda name for ' + iso); return [iso, dial, e, f, rw[iso]]; });
const q = (s) => JSON.stringify(s);
fs.writeFileSync(new URL('../../mobile/src/lib/countries.ts', import.meta.url), `// Generated by scripts/data/gen-countries.mjs: do not edit by hand.
// [ISO country, calling code (digits, no +), English name, French name, Kinyarwanda name]
export type Country = { iso: string; dial: string; en: string; fr: string; rw: string };
const ROWS: [string, string, string, string, string][] = [
${rows.map((r) => '  [' + r.map(q).join(', ') + '],').join('\n')}
];
export const COUNTRIES: Country[] = ROWS.map(([iso, dial, en, fr, rw]) => ({ iso, dial, en, fr, rw }));
`);
fs.writeFileSync(new URL('../../backend/src/util/countries.ts', import.meta.url), `// Generated by scripts/data/gen-countries.mjs: do not edit by hand. ISO country and calling code (digits); +1 islands carry their area code.
export const DIAL_CODES: [string, string][] = ${JSON.stringify(rows.map((r) => [r[0], r[1]]))};
`);
console.log('countries:', rows.length);
